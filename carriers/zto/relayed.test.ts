import { describe, expect, it } from 'vitest';
import { relayedZtoText } from './relayed.js';

describe('relayed ZTO sentences', () => {
  it('keeps the sentence and its city without the couriers, phones, pickup point or courtesy', () => {
    const cases: [string, string, string?][] = [
      ['【西安市】 西安长安常宁分部（029-12345678）某某（13800000000） 已揽收', '西安长安常宁分部 已揽收', '西安市'],
      ['【西安市】 快件已由西安曲江二部某某某（13800000000）揽收（如遇问题无需找商家/平台，请致电【客服热线：029-12345678】更快解决）',
        '快件已揽收', '西安市'],
      ['【广州市】 快件已到达 广州荔城 ，如遇问题请致电【客服热线：95311】', '快件已到达 广州荔城', '广州市'],
      ['【沈阳市】沈阳长白二部 的业务员【长白二部-某某,13800000000】正在为您派件（95720为中通快递员外呼专属号码，请放心接听，如有问题可联系网点:024-12345678）',
        '沈阳长白二部 的业务员正在为您派件', '沈阳市'],
      ['深圳园山 快递员【某某,13800000000】正在为您派件（95720为中通快递员外呼专属号码，请放心接听。网点电话：0755-12345678）',
        '深圳园山 快递员正在为您派件'],
      ['【沈阳市】 快件已在 丰巢 的【某小区南门外丰巢柜1号柜】暂放，【取件地址：某小区南门外丰巢柜1号柜】，请及时取件。如有疑问请联系业务员：13800000000',
        '快件已在 丰巢暂放，请及时取件', '沈阳市'],
      ['【沈阳市】 您的快递已签收，签收人在【某小区南门外丰巢柜1号柜】取件。如有疑问请联系业务员：13800000000。感谢使用中通快递',
        '您的快递已签收', '沈阳市'],
      ['您的快件已送达，如遇问题请联系快递员【某某：13800000000】，无需找商家/平台。签收人：公司前台 ，网点电话：0755-12345678', '您的快件已送达'],
      ['快件已送达【菜鸟-某某学院菜鸟驿站，电话：13800000000】，取件地址：某某路一号，请及时取件。如遇取件码问题请联系快递员【某某：13800000000】',
        '快件已送达，请及时取件'],
      ['您的快件已妥投，已在代收点取出。如遇问题请联系【菜鸟-某某学院菜鸟驿站，电话：13800000000】,无需找商家/平台。', '您的快件已妥投，已在代收点取出'],
    ];
    for (const [raw, description, city] of cases) {
      expect(relayedZtoText(raw), raw).toEqual({ description, ...(city ? { city } : {}) });
    }
  });

  it('leaves a sentence without contacts as it is', () => {
    expect(relayedZtoText('【西安市】 快件已发往 沈阳转运中心')).toEqual({ description: '快件已发往 沈阳转运中心', city: '西安市' });
    expect(relayedZtoText('货物到达温哥华机场，准备发往中国，计划24小时内起飞')).toEqual({ description: '货物到达温哥华机场，准备发往中国，计划24小时内起飞' });
    expect(relayedZtoText('【广州口岸】包裹清关完成，进入国内运输环节')).toEqual({ description: '【广州口岸】包裹清关完成，进入国内运输环节' });
  });
});
