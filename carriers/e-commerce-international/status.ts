const WORDINGS: ReadonlyMap<string, Stage> = new Map([...CODES.values()]
  .flatMap(([wording, stage]) => (stage ? [[normalizeStatusWording(wording), stage] as const] : [])));

/** The English text the page shows for a status code. */
export function eciWording(code: string): string | undefined {
  return CODES.get(code)?.[0];
}

/** The stage a status code gives, or without a code, its text. */
export function eciMappedStage(code: string | null, wording: string): Stage | undefined {
  return (code === null ? WORDINGS.get(normalizeStatusWording(wording)) : CODES.get(code)?.[1]) ?? undefined;
}

