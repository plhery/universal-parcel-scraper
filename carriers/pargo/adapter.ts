import type { AdapterFactory, TrackingContext } from '../../core/adapter/index.js';
import { ChallengeError, SchemaError, TransportError } from '../../core/errors/index.js';
import type { CarrierResult } from '../../core/result/index.js';
import { runSteps } from '../../core/runner/index.js';
import { firstAttemptMs, networkRetryStep } from '../../core/runner/networkRetry.js';
import { NOOP_RECORDER, type StepRecorder } from '../../core/telemetry/index.js';
import { awsWafAction } from '../../core/transport/awsWaf.js';
import { decodeText, fetchBounded, userAgentOf } from '../../core/transport/index.js';
import { normalizePargoNumber, PARGO_MAX_BYTES, PARGO_ORIGIN, parsePargo, PROVIDER } from './parser.js';

export { normalizePargoNumber, parsePargo } from './parser.js';

const REDIRECTS = [301, 302, 303, 307, 308];
const DEFAULT_BUDGET_MS = 15_000;
// A block page CloudFront or a firewall in front of the tracker could give instead of its reply.
const CHALLENGE = /awswaf|gokuProps|_cf_chl_opt|cf-turnstile|Request blocked|Generated by cloudfront|<title>\s*(?:ERROR|403|Access Denied|Just a moment|Attention Required)/i;

/** The lookup the tracking page on track.pargo.co.za makes for the code typed in. */
export const pargoLookupUrl = (number: string): string => `${PARGO_ORIGIN}/events/orders/${encodeURIComponent(number)}`;

export class PargoTracker {
  constructor(private readonly options: { fetcher?: typeof fetch; recorder?: StepRecorder; userAgent?: string } = {}) {}

  /** The page's own request: a GET with a JSON content type, no session, token or cookie. */
  private async read(number: string, signal: AbortSignal, timeoutMs: number): Promise<CarrierResult> {
    const { response, bytes } = await fetchBounded(pargoLookupUrl(number), { signal, headers: {
      Accept: '*/*', 'Content-Type': 'application/json', Referer: `${PARGO_ORIGIN}/`, 'User-Agent': userAgentOf(this.options.userAgent),
    } }, { provider: PROVIDER, timeoutMs: Math.max(1, Math.floor(timeoutMs)), maxBytes: PARGO_MAX_BYTES, redirect: 'manual',
      fetcher: this.options.fetcher, allowHttpStatuses: [...REDIRECTS, 403, 404, 410, 422] });
    const body = decodeText(bytes);
    const json = /^application\/json\b/i.test(response.headers.get('content-type') ?? '');
    if (awsWafAction(response.headers) || (!json && CHALLENGE.test(body.slice(0, 64_000)))) {
      throw new ChallengeError(PROVIDER, 'Pargo answered with a block page', { status: response.status });
    }
    if (REDIRECTS.includes(response.status)) throw new TransportError(PROVIDER, 'Pargo redirected its tracking lookup', { status: response.status });
    if (response.status === 403) throw new ChallengeError(PROVIDER, 'Pargo refused the lookup', { status: 403 });
    // The tracker answers an unknown code with HTTP 422 and its error; a missing route is a moved lookup.
    if (response.status === 404 || response.status === 410) throw new TransportError(PROVIDER, 'Pargo tracking lookup is unavailable', { status: response.status });
    if (!json) throw new SchemaError(PROVIDER, 'Pargo answered with a page instead of its tracking reply');
    let payload: unknown;
    try {
      payload = JSON.parse(body);
    } catch (error) {
      throw new SchemaError(PROVIDER, 'Pargo returned a reply that is not JSON', { cause: error });
    }
    return parsePargo(payload, number);
  }

  async fetch(raw: string, context: TrackingContext = {}): Promise<CarrierResult> {
    const number = normalizePargoNumber(raw);
    // A read that fails to reach the tracker, or hangs, is sent once more: the first try gets half of the budget.
    return runSteps({ carrier: PROVIDER, budgetMs: context.budgetMs ?? DEFAULT_BUDGET_MS, signal: context.signal,
      recorder: this.options.recorder ?? NOOP_RECORDER }, [
      { id: 'direct', run: ({ signal, remainingMs }) => this.read(number, signal, firstAttemptMs(remainingMs)) },
      networkRetryStep(({ signal, remainingMs }) => this.read(number, signal, remainingMs)),
    ]);
  }
}

export const adapter: AdapterFactory = (environment) => {
  const tracker = new PargoTracker({ fetcher: environment.fetcher, recorder: environment.recorder, userAgent: environment.userAgent });
  return {
    id: PROVIDER, recordsSteps: true, steps: ['direct', 'retry'],
    track: (input, context) => tracker.fetch(input.number, context),
  };
};
