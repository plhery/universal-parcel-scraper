/*
 * Generates generated/scanTemplates.ts: the scan templates the carriers' statuses.json entries name, by
 * carrier, keyed by provider code or by wording in `normalizeStatusWording` form, with the wording's language.
 *
 * An entry keys its template by its code when it has one and no wording, or a wording with a placeholder
 * such as <town>; otherwise by its wording, and by its `english` too. data/scan-templates.json holds the
 * templates' text in every language. The script fails on a template that is not there, an entry without a
 * language, a stage the template's disagrees with, and two templates for one key of a carrier.
 * `--check` fails when the committed file is stale.
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'generated', 'scanTemplates.ts');
const read = (file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));

/** The same as `normalizeStatusWording` in core/status/statusMap.ts. */
const normalize = (wording) => wording.toLocaleLowerCase('en-US').trim().split(/\s+/).join(' ').slice(0, 500);
const placeholder = /<[^>]+>|…/;

const { languages, templates } = read('data/scan-templates.json');
const stages = new Set(read('data/stages.json'));
const problems = [];
for (const [id, template] of Object.entries(templates)) {
  if (!/^[a-z][a-z0-9_]*$/.test(id)) problems.push(`template ${id}: the id is not snake_case`);
  if (!stages.has(template.stage)) problems.push(`template ${id}: unknown stage ${template.stage}`);
  const given = Object.keys(template.text);
  if (given.join() !== languages.join()) problems.push(`template ${id}: needs ${languages.join(', ')} in that order`);
  for (const language of languages) {
    const text = template.text[language];
    if (typeof text !== 'string' || !text || text !== text.trim()) problems.push(`template ${id}: no ${language} text`);
  }
}

const carriers = {};
for (const folder of readdirSync(path.join(root, 'carriers')).sort()) {
  const file = `carriers/${folder}/statuses.json`;
  if (!existsSync(path.join(root, file))) continue;
  const codes = new Map();
  const wordings = new Map();
  const add = (keys, key, value, at) => {
    const known = keys.get(key);
    if (known && (known[0] !== value[0] || known[1] !== value[1])) {
      problems.push(`${file} entry ${at}: ${JSON.stringify(key)} is already ${known.join('/')}, not ${value.join('/')}`);
    } else keys.set(key, value);
  };
  read(file).entries.forEach((entry, at) => {
    if (entry.template === undefined) return;
    const template = templates[entry.template];
    if (!template) return problems.push(`${file} entry ${at}: unknown template ${entry.template}`);
    if (!entry.language) return problems.push(`${file} entry ${at}: a templated entry needs its language`);
    if (entry.stage && entry.stage !== template.stage) {
      return problems.push(`${file} entry ${at}: stage ${entry.stage}, but ${entry.template} is ${template.stage}`);
    }
    if (entry.code !== undefined && (!entry.wording || placeholder.test(entry.wording))) {
      add(codes, String(entry.code), [entry.template, entry.language], at);
    } else if (entry.wording && !placeholder.test(entry.wording)) {
      add(wordings, normalize(entry.wording), [entry.template, entry.language], at);
      if (entry.english) add(wordings, normalize(entry.english), [entry.template, 'en'], at);
    } else problems.push(`${file} entry ${at}: a templated entry needs a code or a wording without a placeholder`);
  });
  if (codes.size || wordings.size) {
    carriers[folder] = {
      ...(codes.size ? { codes: Object.fromEntries([...codes].sort(([a], [b]) => a.localeCompare(b))) } : {}),
      ...(wordings.size ? { wordings: Object.fromEntries([...wordings].sort(([a], [b]) => a.localeCompare(b))) } : {}),
    };
  }
}
if (problems.length) throw new Error(`Scan templates:\n${problems.join('\n')}`);

const content = [
  '/* This file is generated by scripts/generate-scan-templates.mjs from the carriers\' statuses.json. Do not edit. */',
  '',
  '/** A scan template\'s id and the language of the carrier wording it stands for. */',
  'export type ScanTemplateKey = readonly [template: string, language: string];',
  '',
  '/** By carrier: the templates its scans take, by provider code and by `normalizeStatusWording` wording. */',
  'export const SCAN_TEMPLATE_KEYS: Readonly<Record<string, {',
  '  readonly codes?: Readonly<Record<string, ScanTemplateKey>>;',
  '  readonly wordings?: Readonly<Record<string, ScanTemplateKey>>;',
  '}>> = {',
  ...Object.entries(carriers).flatMap(([carrier, keys]) => [
    `  ${JSON.stringify(carrier)}: {`,
    ...Object.entries(keys).flatMap(([kind, map]) => [
      `    ${kind}: {`,
      ...Object.entries(map).map(([key, value]) => `      ${JSON.stringify(key)}: ${JSON.stringify(value)},`),
      '    },',
    ]),
    '  },',
  ]),
  '};',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== content) {
    throw new Error('generated/scanTemplates.ts is stale. Run node scripts/generate-scan-templates.mjs.');
  }
  console.log('Scan templates are current.');
} else {
  writeFileSync(outputPath, content);
  console.log(`Wrote ${outputPath}: ${Object.keys(carriers).length} carriers.`);
}
