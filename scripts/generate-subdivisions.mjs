// Builds places/subdivisions.json: each country's ISO 3166-2 subdivision codes of two letters,
// which carriers can write after a town ("BENTIVOGLIO (BO)", "CURITIBA - PR", "Hebron, KY") and
// which can also be a country's code.
//
// Source: Unicode CLDR's subdivision validity data (ISO 3166-2 codes), Unicode-3.0 licence,
// https://github.com/unicode-org/cldr/blob/<release>/common/validity/subdivision.xml.
// Subdivisions CLDR aliases to a country of their own ("overlong": Guadeloupe, Puerto Rico,
// Hong Kong) are left out: their code names that country. Former codes stay, as carriers still
// write them (Sardinia's "OT" for Olbia-Tempio). Numeric codes and codes of one or three letters
// are left out: no country has them.
//
// Run: node scripts/generate-subdivisions.mjs [CLDR release tag].
import { writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const release = process.argv[2] ?? 'release-49';
const base = `https://raw.githubusercontent.com/unicode-org/cldr/${release}/common`;

async function text(path) {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

const validity = await text('validity/subdivision.xml');
const metadata = await text('supplemental/supplementalMetadata.xml');
const sections = ['regular', 'deprecated'].map((status) => {
  const section = new RegExp(`idStatus='${status}'>[^\\n]*\\n([\\s\\S]*?)<\\/id>`).exec(validity)?.[1];
  if (!section) throw new Error(`subdivision.xml: no ${status} subdivisions`);
  return section;
});

// "ad02~8" is ad02 to ad08: the range varies the last character.
const ids = sections.join(' ').split(/\s+/).filter(Boolean).flatMap((token) => {
  const [start, end] = token.split('~');
  if (end === undefined) return [start];
  if (end.length !== 1) throw new Error(`subdivision.xml: unexpected range ${token}`);
  const from = start.charCodeAt(start.length - 1);
  return Array.from({ length: end.charCodeAt(0) - from + 1 }, (_, offset) => start.slice(0, -1) + String.fromCharCode(from + offset));
});
const overlong = new Set([...metadata.matchAll(/<subdivisionAlias type="([a-z]{2})[a-z0-9]+" replacement="([A-Z]{2})" reason="overlong"/g)]
  .map(([, country, replacement]) => `${country.toUpperCase()}-${replacement}`));

const regions = {};
for (const id of new Set(ids)) {
  const country = id.slice(0, 2).toUpperCase();
  const code = id.slice(2).toUpperCase();
  if (!/^[A-Z]{2}$/.test(code) || overlong.has(`${country}-${code}`)) continue;
  (regions[country] ??= []).push(code);
}
const sorted = Object.fromEntries(Object.keys(regions).sort().map((country) => [country, regions[country].sort().join(' ')]));
await writeFile(join(root, 'places/subdivisions.json'), `${JSON.stringify({
  source: `Unicode CLDR ${release}, common/validity/subdivision.xml (ISO 3166-2), generated by scripts/generate-subdivisions.mjs`,
  license: 'Unicode-3.0',
  regions: sorted,
}, null, 2)}\n`);
console.log(`${Object.values(regions).reduce((sum, codes) => sum + codes.length, 0)} codes in ${Object.keys(regions).length} countries`);
