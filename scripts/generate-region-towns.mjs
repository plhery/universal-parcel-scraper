/*
 * Generates generated/regionTowns.ts: the towns of the US
 * states and Canadian provinces whose postal code also names a single-clock
 * country (DE Delaware or Germany, IL Illinois or Israel, IN Indiana or India,
 * MT Montana or Malta, NL Newfoundland and Labrador or the Netherlands, SK
 * Saskatchewan or Slovakia). Carriers write "Chicago, IL" and "Koeln, DE"
 * alike, so only the town tells them apart.
 *
 * Source: the server's gazetteer, places/places.tsv.br (GeoNames
 * towns of 1,000 people or more, CC BY 4.0). A town whose name the country
 * also has, for at least as many people, is left out: "Salem, IN" stays in
 * India.
 *
 * It also lists two island groups that keep another clock than their country:
 * the Canary Islands (ES-CN) and the Azores (PT-20), by their towns and the
 * names of the islands. A carrier that writes only "SPAIN" after a town leaves
 * the town to tell them apart. A name the rest of the country also has is left
 * out, whatever its size: the mainland stays the reading for a name both have.
 *
 * Town keys must match `townKey` in core/time.
 * `--check` fails when the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliDecompressSync } from 'node:zlib';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const gazetteer = path.resolve(packageRoot, 'places/places.tsv.br');
const outputPath = path.join(packageRoot, 'generated', 'regionTowns.ts');

// Region code -> its country and GeoNames admin1 code, and the country the same code names.
const REGIONS = {
  DE: { country: 'US', admin1: 'DE', other: 'DE' },
  IL: { country: 'US', admin1: 'IL', other: 'IL' },
  IN: { country: 'US', admin1: 'IN', other: 'IN' },
  MT: { country: 'US', admin1: 'MT', other: 'MT' },
  NL: { country: 'CA', admin1: '05', other: 'NL' },
  SK: { country: 'CA', admin1: '11', other: 'SK' },
};

// Island group code (ISO 3166-2) -> its country and GeoNames admin1 code, and names that are not towns.
const ISLANDS = {
  'ES-CN': { country: 'ES', admin1: '53', names: ['Tenerife', 'Gran Canaria', 'Lanzarote', 'Fuerteventura', 'La Palma', 'La Gomera', 'El Hierro', 'La Graciosa', 'Las Palmas'] },
  'PT-20': { country: 'PT', admin1: '23', names: ['São Miguel', 'Terceira', 'Faial', 'Pico', 'São Jorge', 'Graciosa', 'Flores', 'Corvo', 'Santa Maria'] },
};

/** Same as `townKey` in core/time: "St. John's" and "SAINT JOHNS" are both "stjohns". */
function townKey(name) {
  return name.normalize('NFD').replace(/\p{Mn}/gu, '').toLowerCase()
    .replace(/\bsaint\b/g, 'st').replace(/\bsainte\b/g, 'ste').replace(/\bmount\b/g, 'mt').replace(/\bfort\b/g, 'ft')
    .replace(/[^a-z0-9]/g, '');
}

function render() {
  // P, name, ascii name, country, admin1, admin2, latitude, longitude, thousands of people, alternates
  const towns = brotliDecompressSync(readFileSync(gazetteer)).toString('utf8').split('\n')
    .filter((line) => line.startsWith('P\t')).map((line) => line.split('\t'));
  const keys = (town) => [...new Set([townKey(town[1]), townKey(town[2])])].filter(Boolean);
  const entries = Object.entries(REGIONS).map(([code, { country, admin1, other }]) => {
    const abroad = new Map();
    for (const town of towns.filter((row) => row[3] === other)) {
      for (const key of keys(town)) abroad.set(key, Math.max(abroad.get(key) ?? 0, Number(town[8])));
    }
    const names = new Set();
    for (const town of towns.filter((row) => row[3] === country && row[4] === admin1)) {
      for (const key of keys(town)) if (!abroad.has(key) || abroad.get(key) < Number(town[8])) names.add(key);
    }
    return `  ${code}: '${[...names].sort().join('|')}',`;
  });
  const islands = Object.entries(ISLANDS).map(([code, { country, admin1, names: islandNames }]) => {
    const elsewhere = new Set(towns.filter((row) => row[3] === country && row[4] !== admin1).flatMap(keys));
    const names = new Set([...islandNames.map(townKey), ...towns.filter((row) => row[3] === country && row[4] === admin1).flatMap(keys)]
      .filter((key) => !elsewhere.has(key)));
    return `  '${code}': '${[...names].sort().join('|')}',`;
  });
  return [
    '/* This file is generated by scripts/generate-region-towns.mjs. Do not edit. */',
    '// Towns from GeoNames (https://www.geonames.org), CC BY 4.0, through places.',
    '',
    '/**',
    ' * Town keys of the US states and Canadian provinces whose code also names a single-clock country,',
    ' * and of the island groups that keep another clock than their country.',
    ' */',
    'export const REGION_TOWNS: Readonly<Record<string, string>> = {',
    ...entries,
    ...islands,
    '};',
    '',
  ].join('\n');
}

const content = render();
if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== content) {
    throw new Error('generated/regionTowns.ts is stale. Run node scripts/generate-region-towns.mjs.');
  }
  console.log('Region towns are current.');
} else {
  writeFileSync(outputPath, content);
  console.log(`Wrote ${outputPath}.`);
}
